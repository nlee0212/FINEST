def find_error_sent_ratio(data_list,response_len):
    # error_types = set([data['error_category'] for data in data_list if data['error_category']!=''])
    sents_dict = defaultdict(set)
    overall_sents = set()

    if response_len == None:
        return [None,None]
    
    for data in data_list:
        if 'error_category' in data and data['error_category'] != '':
            if isinstance(data['sentence_num'],list):
                if 'all' in data['sentence_num']:
                    sents_dict[data['error_category']].update(range(1,response_len+1))
                    overall_sents.update(range(1,response_len+1))
                else:
                    data['sentence_num'] = [int(num) for num in data['sentence_num'] if isinstance(num,int) or (isinstance(num,str) and num.isdigit())]
                    sents_dict[data['error_category']].update(data['sentence_num'])
                    overall_sents.update(data['sentence_num'])
            elif isinstance(data['sentence_num'],int):
                sents_dict[data['error_category']].add(data['sentence_num'])
                overall_sents.add(data['sentence_num'])
            elif isinstance(data['sentence_num'],str) and data['sentence_num'].isdigit():
                data['sentence_num'] = int(data['sentence_num'])
                sents_dict[data['error_category']].add(data['sentence_num'])
                overall_sents.add(data['sentence_num'])

    overall_sents -= set(['none'])
    for k in sents_dict:
        sents_dict[k] -= set(['none'])
        
    ratio_dict = {error:len(set(range(1,response_len+1)) & sents)/response_len for error,sents in sents_dict.items()}
    final_ratio = len(set(range(1,response_len+1)) & overall_sents)/response_len

    return [ratio_dict,final_ratio]

def get_core_app(question,model_path,model,tokenizer,temperature,top_p,max_tokens,gpt_azure,core_question_dict=None):
    if core_question_dict == None or question not in core_question_dict:
        print("generate core question and keywords")
        extract_core_app_prompt = extract_core_app(question)
        res = get_model_response(model_path,extract_core_app_prompt,model,tokenizer,temperature,top_p,max_tokens,gpt_azure)
        
        core_question = re.search(r'core question: (.+)\n',res).group(1)
        keywords = re.search(r'keywords: (.+)',res).group(1)
        
        if isinstance(core_question_dict,dict):
            core_question_dict[question] = (core_question,keywords)
    else:
        if isinstance(core_question_dict,dict):
            core_question,keywords = core_question_dict[question]

    return core_question,keywords

class NaNEncoder(json.JSONEncoder):
    def default(self, obj):
        if isinstance(obj, float) and math.isnan(obj):
            return ''  
        return super().default(obj)

